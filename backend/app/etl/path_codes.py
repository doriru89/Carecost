"""The extraction code list follows the care paths (R9): every ``cpts`` code of every care path
is extracted, so a path code can never be missing from the data again.

    cd backend
    uv run --frozen python -m app.etl codes sync    # rewrite data/etl/path_codes.yaml
    uv run --frozen python -m app.etl codes check   # exit 1 when it is stale (CI + a test)
    uv run --frozen python -m app.etl --data-dir D codes check --data   # + the extracted data

``data/etl/path_codes.yaml`` is generated from ``data/care_paths/paths/*.yaml`` (step ``cpts`` and
the codes of ``ai_potential`` boxes). :func:`app.etl.config.load_codes` adds its codes to the
hand-written ``codes.yaml`` list, so hospital normalize, the TiC code filter and the pack all
read one list. A path's ``scope.area`` picks the ``codes.yaml`` domain through
``path_area_domains`` in ``codes.yaml``; an area with no mapping fails ``sync`` loudly.

``check --data`` also reads what was really extracted: every current TiC run records the code
list it was cut with (``run.json`` ``target_codes``) and every normalized hospital file its
``target_codes`` in the stats; a path code outside either list means a re-extraction is due
(``tic extend`` + ``tic normalize``, ``normalize --force``).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

from app.etl.config import CONFIG_DIR, Paths

PATH_CODES_FILE = "path_codes.yaml"
HEADER = (
    "# GENERATED by `cd backend && uv run --frozen python -m app.etl codes sync` from\n"
    "# data/care_paths/paths/*.yaml (R9). Do not edit; re-run sync after adding a care path.\n"
    "# code -> the codes.yaml domain(s) (via path_area_domains) and the path steps using it.\n"
)


class PathCodesError(RuntimeError):
    pass


def _paths_dir() -> Path:
    from app.care_paths.loader import CARE_PATHS_DIR

    return CARE_PATHS_DIR / "paths"


def derive(
    paths_dir: Path | None = None, config_dir: Path | None = None
) -> dict[str, dict[str, Any]]:
    """code -> {domains: [...], used_by: ["path:step", ...]} from the care-path YAML."""
    from app.care_paths.loader import load_paths

    cfg = yaml.safe_load(((config_dir or CONFIG_DIR) / "codes.yaml").read_text())
    area_map: dict[str, str] = cfg.get("path_area_domains") or {}
    out: dict[str, dict[str, Any]] = {}
    unmapped: set[str] = set()
    for pid, path in sorted(load_paths(paths_dir or _paths_dir()).items()):
        area = path.scope.area
        dom = area_map.get(area)
        if dom is None:
            unmapped.add(area)
            continue
        if dom not in (cfg.get("domains") or {}):
            raise PathCodesError(f"path_area_domains: {area} -> {dom!r} is not a codes.yaml domain")
        for st in path.steps:
            refs = [(c.code, "") for c in st.cpts]
            refs += [(c.code, " (ai)") for ai in st.ai_potential for c in ai.cpts]
            for code, tag in refs:
                e = out.setdefault(code, {"domains": [], "used_by": []})
                if dom not in e["domains"]:
                    e["domains"].append(dom)
                use = f"{pid}:{st.id}{tag}"
                if use not in e["used_by"]:
                    e["used_by"].append(use)
    if unmapped:
        raise PathCodesError(
            f"care-path area(s) {sorted(unmapped)} have no path_area_domains entry in "
            "data/etl/codes.yaml; add one (e.g. `gi_abdomen: gi`) and re-run `codes sync`"
        )
    for e in out.values():
        e["domains"].sort()
        e["used_by"].sort()
    return dict(sorted(out.items()))


def render(derived: dict[str, dict[str, Any]]) -> str:
    """Every code quoted (``00811`` must never read as a number in any YAML parser)."""
    lines = [HEADER.rstrip("\n"), "version: 1", "codes:"]
    for code, e in derived.items():
        doms = ", ".join(json.dumps(x) for x in e["domains"])
        uses = ", ".join(json.dumps(x) for x in e["used_by"])
        lines.append(f'  "{code}": {{domains: [{doms}], used_by: [{uses}]}}')
    return "\n".join(lines) + "\n"


def sync(paths_dir: Path | None = None, config_dir: Path | None = None) -> tuple[Path, int]:
    d = config_dir or CONFIG_DIR
    derived = derive(paths_dir, d)
    target = d / PATH_CODES_FILE
    tmp = target.with_suffix(".yaml.tmp")
    tmp.write_text(render(derived))
    tmp.replace(target)
    return target, len(derived)


def check(paths_dir: Path | None = None, config_dir: Path | None = None) -> list[str]:
    """Problems with the committed path_codes.yaml (empty list = in sync)."""
    d = config_dir or CONFIG_DIR
    f = d / PATH_CODES_FILE
    derived = derive(paths_dir, d)
    if not f.exists():
        return [f"{f} is missing; run `python -m app.etl codes sync`"]
    have = (yaml.safe_load(f.read_text()) or {}).get("codes") or {}
    probs = []
    for code in sorted(set(derived) - set(have)):
        probs.append(
            f"{code} ({', '.join(derived[code]['used_by'])}) is a care-path code missing from "
            f"extraction ({PATH_CODES_FILE}); run `python -m app.etl codes sync`"
        )
    for code in sorted(set(have) - set(derived)):
        probs.append(f"{code} is in {PATH_CODES_FILE} but no care path uses it; run `codes sync`")
    for code in sorted(set(have) & set(derived)):
        if have[code] != derived[code]:
            probs.append(f"{code}: {PATH_CODES_FILE} entry is stale; run `codes sync`")
    return probs


def check_data(paths: Paths, codes: set[str], hospital_codes: set[str] | None = None) -> list[str]:
    """Codes the extracted data was not cut for. ``codes``: the TiC list (codes.yaml + path codes
    + visit codes); ``hospital_codes``: the hospital normalize list (codes.yaml + path codes)."""
    hospital_codes = codes if hospital_codes is None else hospital_codes
    probs: list[str] = []
    tic = paths.data / "intermediate" / "tic"
    for d in sorted(tic.glob("tic_*")) if tic.exists() else []:
        cur = d / "CURRENT"
        if not cur.exists():
            continue
        run = json.loads((d / cur.read_text().strip() / "run.json").read_text())
        got = run.get("target_codes")
        if got is None:
            probs.append(f"{d.name}: run.json has no target_codes (cut before R9); `tic extend`")
            continue
        miss = sorted(codes - set(got))
        if miss:
            probs.append(f"{d.name}: not extracted for {miss}; `tic extend --network {d.name}`")
    norm = paths.data / "intermediate" / "normalized"
    for d in sorted(norm.glob("*")) if norm.exists() else []:
        for s in sorted(d.glob("*.stats.json")):
            st = json.loads(s.read_text())
            got = st.get("target_codes")
            if got is None:
                probs.append(
                    f"{d.name}/{s.name}: no target_codes (cut before R9); normalize --force"
                )
                continue
            miss = sorted(hospital_codes - set(got))
            if miss:
                probs.append(f"{d.name}: not normalized for {miss}; normalize --force")
    return probs


def cmd_codes(a: Any, paths: Paths) -> int:
    from app.etl.config import load_codes

    if a.codes_cmd == "sync":
        f, n = sync(config_dir=a.config_dir)
        load_codes.cache_clear()
        print(f"SYNC   {f}: {n} care-path codes", flush=True)
        return 0
    probs = check(config_dir=a.config_dir)
    if getattr(a, "data", False):
        load_codes.cache_clear()
        from app.etl.tic.networks import target_codes

        probs += check_data(paths, target_codes(a.config_dir), load_codes(a.config_dir).codes)
    for p in probs:
        print(f"FAIL   {p}", flush=True)
    if not probs:
        print("OK     every care-path code is in the extraction code list", flush=True)
    return 1 if probs else 0


def add_parser(sub: Any) -> None:
    p = sub.add_parser("codes", help="care-path codes -> extraction code list (R9)")
    cs = p.add_subparsers(dest="codes_cmd", required=True)
    cs.add_parser("sync", help="rewrite data/etl/path_codes.yaml from the care paths")
    c = cs.add_parser("check", help="exit 1 when a care-path code is missing from extraction")
    c.add_argument("--data", action="store_true", help="also check the extracted data")
