COLS = ["code", "entity_id", "payer_id", "amount", "negotiated_pct", "modifiers", "billing_class",
        "tic_service_codes", "tic_site_ids", "tic_business_name", "source_id", "tic_match"]  # fmt: skip
KNOWN = [  # research-v3 tins.tsv + AFC (the TINs the brief starts from)
    ("272343207", "AFC Urgent Care (AFC Physicians of MA)"), ("455391610", "CareWell UC Centers of MA"),
    ("352533673", "CareWell Urgent Care"), ("042807148", "MGPO (MGH physicians)"),
    ("043466314", "Brigham & Women's Physicians Org"), ("222768204", "HMFP at BIDMC"),
    ("320058309", "AP HMFP Surgery"), ("043397450", "Atrius Health"), ("042704683", "Lahey Clinic"),
    ("222560501", "MGB Medical Group"), ("472248298", "BILH Primary Care"),
    ("043235796", "NE Baptist Medical Associates"), ("820671467", "Boston Orthopaedic & Spine"),
    ("043400617", "Tufts Medical Center Inc"), ("473046563", "Tufts MC Community Care"),
    ("043354353", "BU Family Medicine"), ("043283573", "BUMC Radiologists"),
    ("043276227", "BU Medical Center (physicians)"), ("042697983", "Massachusetts General Hospital"),
    ("042103881", "Beth Israel Deaconess MC"), ("043314093", "Boston Medical Center"),
]  # fmt: skip
SHOW = ["99203", "99213", "S9083", "20610", "73030"]


def _fmt(v: float | None) -> str:
    return "" if v is None else f"${v:,.2f}"


def build_report(paths: Paths, nets: list[TicNetwork], out: Path | None = None) -> dict[str, Any]:
    out = out or (CONFIG_DIR.parents[1] / "docs" / "etl")
    codes = load_codes()
    vmap = load_visit_map()
    runs: list[tuple[TicNetwork, dict[str, Any], Path]] = []
    rows: list[dict[str, Any]] = []
    for net in nets:
        d = current_dir(paths, net.source_id)
        if d is None or not (d / "rate_row.parquet").exists():
            continue
        run = json.loads((d / "run.json").read_text())
        runs.append((net, run, d))
        rows += pq.read_table(d / "rate_row.parquet", columns=COLS).to_pylist()
    usable = [r for r in rows if r["amount"] is not None]
    payers = sorted({n.payer_id for n, _, _ in runs})

    L: list[str] = ["# TiC coverage (insurer negotiated rates)", ""]
    L += [
        "Generated by `python -m app.etl tic report`. One row in `rate_row` = one negotiated price ×",
        "one provider group (TIN + NPI list) that matches the Boston target list",
        "(`data/etl/tic_provider_targets.csv`: census org NPIs → every TIN they bill under, plus",
        "census TINs). Staging keeps every provider group of every file. Usable = dollar amount;",
        "percentage-of-charges rows are counted separately.",
        "",
        f"**{len(runs)} networks loaded, {len(rows):,} rate rows ({len(usable):,} with a dollar amount), "
        f"{len({r['entity_id'] for r in usable}):,} TIN/NPI entities.**",
        "",
        "## Networks loaded",
        "",
        "| payer | network | file | file date | size (.gz/.zip) | raw | sha256 | fetched_at | pass s | GB/s raw | index MB | target items | prices staged | provider groups | rate rows |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for net, run, _d in runs:
        st, nm = run["stage"], run.get("normalize") or {}
        L.append(
            f"| {net.payer_id} | {net.label} | `{run['source_file'][:60]}` | {run.get('last_updated_on')} | "
            f"{run['comp_bytes'] / 1e6:,.0f} MB | {run['raw_bytes'] / 1e9:,.1f} GB | `{run['source_sha256'][:12]}` | "
            f"{(run.get('fetch') or {}).get('fetched_at')} | {run['seconds_pass']} | {run['inflate_gb_s']} | "
            f"{run['index_bytes'] / 1e6:.1f} | {st['target_items']} | {st['price_rows']:,} | {st['group_rows']:,} | "
            f"{nm.get('rate_rows', 0):,} |"
        )
    # code x payer
    cell_rows: dict[tuple[str, str], int] = Counter()
    cell_tins: dict[tuple[str, str], set[str]] = defaultdict(set)
    pct: Counter[tuple[str, str]] = Counter()
    for r in rows:
        k = (r["code"], r["payer_id"])
        if r["amount"] is None:
            pct[k] += 1
            continue
        cell_rows[k] += 1
        cell_tins[k].add(r["entity_id"])
    all_codes = sorted(codes.codes | vmap.all_codes)
    L += [
        "",
        "## Code × payer (Boston-target rows / distinct TINs)",
        "",
        "| code | what | " + " | ".join(payers) + " |",
        "|---|---|" + "---|" * len(payers),
    ]
    for c in all_codes:
        cells = []
        for p in payers:
            n = cell_rows.get((c, p), 0)
            cells.append(
                f"{n:,} / {len(cell_tins.get((c, p), ()))}"
                if n
                else ("%-only" if pct.get((c, p)) else "—")
            )
        L.append(
            f"| {c} | {codes.description(c) or ('visit add-on' if c in vmap.add_ons else 'visit')} | "
            + " | ".join(cells)
            + " |"
        )
    # MRF-missing codes: whole-file counts from the staged items (all providers), plus Boston rows
    L += [
        "",
        "## Codes the hospital MRFs lack",
        "",
        "Hospital MRFs (12 files) have no payer rate for these. `file` = rate groups for the code in",
        "the whole file (any provider, from staged prices); `Boston` = rows / TINs for target providers.",
        "",
        "| code | " + " | ".join(f"{p} file" + " | " + f"{p} Boston" for p in payers) + " |",
        "|---|" + "---|---|" * len(payers),
    ]
    file_counts: Counter[tuple[str, str]] = Counter()
    for net, _run, d in runs:
        t = pq.read_table(
            d / "prices.parquet", columns=["billing_code", "price_ordinal"]
        ).to_pylist()
        for r in t:
            if r["billing_code"] in MRF_MISSING and r["price_ordinal"] >= 0:
                file_counts[(r["billing_code"], net.payer_id)] += 1
    for c in MRF_MISSING:
        cells = []
        for p in payers:
            cells.append(f"{file_counts.get((c, p), 0):,}")
            n = cell_rows.get((c, p), 0)
            cells.append(f"{n:,} / {len(cell_tins.get((c, p), ()))}" if n else "—")
        L.append(f"| {c} | " + " | ".join(cells) + " |")
    # known Boston TINs
    L += [
        "",
        "## Known Boston TINs (median $ over all matching rows, unmodified codes, all POS)",
        "",
        "| TIN | who | payers with any rate | " + " | ".join(SHOW) + " |",
        "|---|---|---|" + "---|" * len(SHOW),
    ]
    by_tin: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for r in usable:
        by_tin[r["entity_id"]].append(r)
    for tin, who in KNOWN:
        rs = by_tin.get(f"tin:{tin}", [])
        ps = sorted({r["payer_id"] for r in rs})
        cells = []
        for c in SHOW:
            parts = []
            for p in ps:
                v = [
                    r["amount"]
                    for r in rs
                    if r["code"] == c and r["payer_id"] == p and not r["modifiers"]
                ]
                if v:
                    parts.append(f"{p} {_fmt(statistics.median(v))}")
            cells.append("<br>".join(parts) or "—")
        L.append(f"| {tin} | {who} | {', '.join(ps) or '—'} | " + " | ".join(cells) + " |")
    # census cut
    site_payers: dict[str, set[str]] = defaultdict(set)
    for r in usable:
        for s in (r["tic_site_ids"] or "").split(";"):
            if s:
                site_payers[s].add(r["payer_id"])
    census = _census_sites()
    L += [
        "",
        "## Census cut (research-v3/clinic-census.csv sites with ≥1 TiC dollar rate)",
        "",
        "| category | sites | " + " | ".join(payers) + " | any payer |",
        "|---|---|" + "---|" * (len(payers) + 1),
    ]
    by_cat: dict[str, list[str]] = defaultdict(list)
    for sid, cat in census.items():
        by_cat[cat].append(sid)
    for cat in sorted(by_cat):
        sids = by_cat[cat]
        cells = [str(sum(1 for s in sids if p in site_payers.get(s, ()))) for p in payers]
        anyp = sum(1 for s in sids if site_payers.get(s))
        L.append(f"| {cat} | {len(sids)} | " + " | ".join(cells) + f" | {anyp} |")
    L += [
        "",
        "Match type of rate rows: "
        + ", ".join(f"{k} {v:,}" for k, v in Counter(r["tic_match"] for r in rows).most_common()),
        "",
    ]
    out.mkdir(parents=True, exist_ok=True)
    md = out / "tic_coverage.md"
    atomic_write_text(md, "\n".join(L) + "\n")
    # CSV: code x payer x entity
    agg: dict[tuple[str, str, str], list[float]] = defaultdict(list)
    names: dict[str, str] = {}
    for r in usable:
        agg[(r["code"], r["payer_id"], r["entity_id"])].append(r["amount"])
        names.setdefault(r["entity_id"], r["tic_business_name"])
    tmp = out / ".tic_coverage.csv.tmp"
    with tmp.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(
            [
                "code",
                "payer_id",
                "entity_id",
                "business_name_example",
                "rows",
                "min",
                "median",
                "max",
            ]
        )
        for (c, p, e), v in sorted(agg.items()):
            w.writerow([c, p, e, names.get(e, ""), len(v), min(v), statistics.median(v), max(v)])
    tmp.replace(out / "tic_coverage.csv")
    alias = write_alias_proposals(runs, out / "payer_alias_proposals.csv")
    return {
        "md": md,
        "networks_loaded": len(runs),
        "rate_rows": len(rows),
        "alias_proposals": alias,
    }


def _census_sites() -> dict[str, str]:
    p = CONFIG_DIR / "tic_provider_targets.csv"
    out: dict[str, str] = {}
    with p.open(newline="") as f:
        for r in csv.DictReader(f):
            if r["site_id"]:
                out[r["site_id"]] = r["category"]
    return out


def write_alias_proposals(runs: list[tuple[TicNetwork, dict[str, Any], Path]], path: Path) -> int:
    """TiC payer / plan strings the hospital alias table would not map to the network's payer."""
    res = PayerResolver.load()
    props: dict[tuple[str, str], dict[str, Any]] = {}
    for net, run, _d in runs:
        raw = run.get("reporting_entity_name") or ""
        got = res.resolve(raw, net.label)
        if got.payer_id == net.payer_id:
            continue
        k = (raw, net.payer_id)
        e = props.setdefault(
            k,
            {
                "raw_name": raw,
                "proposed_id": net.payer_id,
                "row_count": 0,
                "evidence": [],
                "resolver_gives": got.payer_id or "(none)",
            },
        )
        e["row_count"] += (run.get("normalize") or {}).get("rate_rows", 0)
        e["evidence"].append(f"{run['source_file']} reporting_entity_name")
    with path.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["raw_name", "proposed_id", "row_count", "evidence", "resolver_gives_today"])
        for e in props.values():
            w.writerow(
                [
                    e["raw_name"],
                    e["proposed_id"],
                    e["row_count"],
                    "; ".join(e["evidence"]),
                    e["resolver_gives"],
                ]
            )
    return len(props)
