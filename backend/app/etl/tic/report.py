"""TiC coverage report -> ``docs/etl/tic_coverage.md`` + ``tic_coverage.csv`` (+ alias proposals).

Usable TiC rate = a ``rate_row`` with a dollar ``amount`` (percentage rows are counted apart).
Sections: networks loaded (file, date, size, sha, timings), code x payer (rows, TINs), the codes
hospital MRFs lack, the known Boston TINs, and the census cut (sites with a rate per payer).
"""

from __future__ import annotations

